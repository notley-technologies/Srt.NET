using System;
using System.Linq;
using System.Net;
using System.Net.Sockets;
using System.Runtime.InteropServices;
using System.Text;
using FsCheck;
using FsCheck.Fluent;
using Srt.Net;
using Srt.Net.Interop;
using Xunit;

namespace Srt.NET.Tests;

/// <summary>
/// Property-based tests (FsCheck) for code that translates data across the native boundary. Generators cover the full
/// input ranges, not FsCheck's small default sizes, and always include the boundary values; a failure reports the
/// counterexample and the seed that reproduces it.
/// </summary>
public sealed class PropertyTests : IClassFixture<RuntimeFixture>
{
    private const int StreamIdLimit = 512;

    private static readonly Config Checked = Config.QuickThrowOnFailure.WithMaxTest(300);
    private static readonly Config CheckedNative = Config.QuickThrowOnFailure.WithMaxTest(100);

    private static Gen<byte> Bytes => ArbMap.Default.GeneratorFor<byte>();

    private static Gen<int> Ports => Gen.OneOf(Gen.Choose(0, ushort.MaxValue), Gen.Elements(0, 1, ushort.MaxValue));

    private static Gen<int> AnyInt => Gen.OneOf(
        Gen.Choose(int.MinValue, int.MaxValue),
        Gen.Choose(-2, 2),
        Gen.Elements(int.MinValue, int.MaxValue));

    // Unicode scalar values: every code point except the surrogate range and NUL, which libsrt treats as a terminator.
    private static Gen<string> Scalars => Gen.OneOf(Gen.Choose(1, 0xD7FF), Gen.Choose(0xE000, 0x10FFFF))
        .Select(char.ConvertFromUtf32);

    [Fact]
    public void Ipv4EndpointsRoundTripThroughTheNativeSocketAddressLayout()
    {
        Gen<IPEndPoint> endpoints =
            from address in Gen.ArrayOf(Bytes, 4)
            from port in Ports
            select new IPEndPoint(new IPAddress(address), port);

        Check.One(Checked, Prop.ForAll(endpoints.ToArbitrary(), RoundTripsThroughNativeMemory));
    }

    [Fact]
    public void Ipv6EndpointsRoundTripThroughTheNativeSocketAddressLayout()
    {
        // Scope IDs only apply to link-local addresses, and modern .NET drops them from other addresses when it decodes a
        // sockaddr_in6, so generate what sockets report: link-local addresses with any scope, other addresses without.
        Gen<IPEndPoint> endpoints =
            from address in Gen.ArrayOf(Bytes, 16)
            from linkLocal in ArbMap.Default.GeneratorFor<bool>()
            from scope in Gen.OneOf(Gen.Choose(0, int.MaxValue), Gen.Elements(0, 1, int.MaxValue))
            from port in Ports
            select new IPEndPoint(CreateIpv6(address, linkLocal, scope), port);

        Check.One(Checked, Prop.ForAll(endpoints.ToArbitrary(), RoundTripsThroughNativeMemory));
    }

    [Fact]
    public void NativeStringsAreReadUpToTheTerminatorAndNeverPastTheBound()
    {
        Gen<(byte[] Bytes, int Bound)> inputs =
            from length in Gen.OneOf(Gen.Choose(0, 600), Gen.Elements(0, 1))
            from bytes in Gen.ArrayOf(Bytes, length)
            from bound in Gen.OneOf(Gen.Choose(0, length), Gen.Constant(length))
            select (bytes, bound);

        Check.One(Checked, Prop.ForAll(inputs.ToArbitrary(), input =>
        {
            // The native buffer holds exactly the generated bytes, so reading past the bound would read outside it.
            int terminator = Array.IndexOf(input.Bytes, (byte)0, 0, input.Bound);
            int length = terminator < 0 ? input.Bound : terminator;
            string expected = Encoding.UTF8.GetString(input.Bytes, 0, length);

            return ReadNative(input.Bytes, input.Bound) == expected;
        }));
    }

    [Fact]
    public void EveryNativeErrorAndRejectionCodeHasDescriptionText()
    {
        // libsrt returns static text for every value: "UNDEFINED ERROR" for unknown error codes, and its generic or
        // application-defined message for unknown rejection reasons.
        Gen<int> codes = Gen.OneOf(
            AnyInt,
            Gen.Elements(Enum.GetValues(typeof(SrtErrorCode)).Cast<int>().ToArray()),
            Gen.Elements(Enum.GetValues(typeof(SrtRejectReason)).Cast<int>().ToArray()),
            Gen.Choose(1000, 2100));

        Check.One(CheckedNative, Prop.ForAll(codes.ToArbitrary(), code =>
            !string.IsNullOrEmpty(SrtErrors.Describe((SrtErrorCode)code))
            && !string.IsNullOrEmpty(SrtErrors.DescribeRejection((SrtRejectReason)code))));
    }

    [Fact]
    public void StreamIdsRoundTripWhenTheirUtf8FormFitsTheNativeLimit()
    {
        using SrtSocket socket = new();

        Check.One(CheckedNative, Prop.ForAll(StreamIds(0, StreamIdLimit).ToArbitrary(), value =>
        {
            socket.SetOption(SrtOptions.StreamId, value);

            return socket.GetOption(SrtOptions.StreamId) == value;
        }));
    }

    [Fact]
    public void StreamIdsLongerThanTheNativeLimitAreRejected()
    {
        using SrtSocket socket = new();

        Check.One(CheckedNative, Prop.ForAll(StreamIds(StreamIdLimit + 1, StreamIdLimit + 64).ToArbitrary(), value =>
            Throws<ArgumentException>(() => socket.SetOption(SrtOptions.StreamId, value))));
    }

    [Fact]
    public void StreamIdsWithUnpairedSurrogatesAreRejectedInsteadOfAltered()
    {
        using SrtSocket socket = new();
        Gen<string> invalid =
            from prefixLength in Gen.Choose(0, 20)
            from prefix in Gen.ArrayOf(Scalars, prefixLength)
            from surrogate in Gen.Choose(0xD800, 0xDFFF)
            from suffixLength in Gen.Choose(0, 3)
            from suffix in Gen.ArrayOf(Scalars, suffixLength)
            select string.Concat(prefix) + (char)surrogate + string.Concat(suffix);

        Check.One(CheckedNative, Prop.ForAll(invalid.ToArbitrary(), value =>
            Throws<ArgumentException>(() => socket.SetOption(SrtOptions.StreamId, value))));
    }

    [Fact]
    public void LingerAcceptsExactlyThePortableTimeoutRangeAndRoundTripsThroughTheSocket()
    {
        using SrtSocket socket = new();
        Gen<int> seconds = Gen.OneOf(AnyInt, Gen.Choose(ushort.MaxValue - 2, ushort.MaxValue + 2), Gen.Choose(0, ushort.MaxValue));

        Check.One(CheckedNative, Prop.ForAll(seconds.ToArbitrary(), value =>
        {
            bool valid = value is >= 0 and <= ushort.MaxValue;
            SrtLinger linger;

            try
            {
                linger = new(true, value);
            }
            catch (ArgumentOutOfRangeException)
            {
                return !valid;
            }

            // Windows stores linger as two 16-bit fields and Unix as two ints; the codec must carry every valid value.
            socket.SetOption(SrtOptions.Linger, linger);
            SrtLinger read = socket.GetOption(SrtOptions.Linger);

            return valid && read.Enabled && read.Seconds == value;
        }));
    }

    private static Gen<string> StreamIds(int minimumBytes, int maximumBytes)
    {
        // Append scalars until the UTF-8 form reaches a target length, so lengths near the limit are common and 1- to
        // 4-byte sequences (including characters outside the BMP, which use surrogate pairs) all appear.
        return from target in Gen.OneOf(Gen.Choose(minimumBytes, maximumBytes), Gen.Elements(minimumBytes, maximumBytes))
               from scalars in Gen.ArrayOf(Scalars, maximumBytes)
               select Fill(scalars, target, maximumBytes);
    }

    private static string Fill(System.Collections.Generic.IEnumerable<string> scalars, int target, int maximumBytes)
    {
        StringBuilder builder = new();
        int bytes = 0;

        foreach (string scalar in scalars)
        {
            int size = Encoding.UTF8.GetByteCount(scalar);

            if (bytes >= target || bytes + size > maximumBytes)
            {
                break;
            }

            builder.Append(scalar);
            bytes += size;
        }

        // Pad with one-byte characters so the length lands on the target exactly.
        return builder.Append('x', Math.Max(0, target - bytes)).ToString();
    }

    private static bool Throws<TException>(Action action)
        where TException : Exception
    {
        try
        {
            action();

            return false;
        }
        catch (TException)
        {
            return true;
        }
    }

    private static IPAddress CreateIpv6(byte[] bytes, bool linkLocal, long scope)
    {
        if (!linkLocal)
        {
            IPAddress address = new(bytes, 0);

            return address.IsIPv6LinkLocal ? new IPAddress(bytes, scope) : address;
        }

        // fe80::/10
        bytes[0] = 0xFE;
        bytes[1] = (byte)(0x80 | (bytes[1] & 0x3F));

        return new IPAddress(bytes, scope);
    }

    private static bool RoundTripsThroughNativeMemory(IPEndPoint endpoint)
    {
        // libsrt hands addresses back as a pointer to a sockaddr; decoding from native memory checks that the codec
        // reads the platform's family field and picks the IPv4 or IPv6 length from it.
        Span<byte> buffer = stackalloc byte[128];
        int length = SocketAddressCodec.Encode(endpoint, buffer);
        IntPtr native = Marshal.AllocHGlobal(length);

        try
        {
            Marshal.Copy(buffer.Slice(0, length).ToArray(), 0, native, length);
            IPEndPoint decoded = SocketAddressCodec.Decode(native);

            // IPEndPoint equality ignores the IPv6 scope, which the native layout must also carry.
            return decoded.Equals(endpoint)
                && (endpoint.AddressFamily != AddressFamily.InterNetworkV6 || decoded.Address.ScopeId == endpoint.Address.ScopeId);
        }
        finally
        {
            Marshal.FreeHGlobal(native);
        }
    }

    private static string ReadNative(byte[] bytes, int bound)
    {
        IntPtr buffer = Marshal.AllocHGlobal(Math.Max(bytes.Length, 1));

        try
        {
            Marshal.Copy(bytes, 0, buffer, bytes.Length);

            return Utf8Interop.Read(buffer, bound);
        }
        finally
        {
            Marshal.FreeHGlobal(buffer);
        }
    }
}
